// VolumeExists implements data.VolumeRestorer. A missing volume is reported as
// false without inventing an engine error; any other failure is surfaced so a
// permission problem is never misread as "target does not exist".
func (c *Compose) VolumeExists(ctx context.Context, volumeName string) (bool, error) {
	res, err := c.run(ctx, execx.Command{
		Name: "docker",
		Args: []string{"volume", "inspect", "--format", "{{.Name}}", volumeName},
	})
	if ctxErr := ctx.Err(); ctxErr != nil {
		return false, ctxErr
	}
	if err != nil {
		return false, err
	}
	if res.Succeeded() {
		return true, nil
	}
	text := strings.ToLower(res.Combined())
	if strings.Contains(text, "no such volume") || strings.Contains(text, "not found") {
		return false, nil
	}
	return false, core.FailCause(fmt.Errorf("docker volume inspect exited with status %d", res.ExitCode), core.Diagnostic{
		Category:    core.CategoryRestoreFailed,
		Severity:    core.SeverityError,
		Message:     msgDataVolumeInspectFailed,
		Detail:      summarize(res.Combined()),
		NextActions: []string{msgDataVolumeInspectAction},
	})
}

// VolumeUsage implements data.VolumeRestorer with a read-only root helper.
func (c *Compose) VolumeUsage(ctx context.Context, volumeName string) (data.VolumeUsage, error) {
	script := `set -e
blocks=$(du -sk /data | awk '{print $1}')
count=$(find /data -mindepth 1 | wc -l)
printf '%s %s\n' "$blocks" "$count"`
	res, err := c.runVolumeHelper(ctx, volumeName, []string{volumeName + ":/data:ro"}, "sh", "-c", script)
	if err != nil {
		return data.VolumeUsage{}, err
	}
	fields := strings.Fields(res.Output)
	if len(fields) != 2 {
		return data.VolumeUsage{}, fmt.Errorf("volume usage helper returned %q", res.Output)
	}
	blocks, err := strconv.ParseInt(fields[0], 10, 64)
	if err != nil {
		return data.VolumeUsage{}, fmt.Errorf("volume usage blocks %q: %w", fields[0], err)
	}
	entries, err := strconv.ParseInt(fields[1], 10, 64)
	if err != nil {
		return data.VolumeUsage{}, fmt.Errorf("volume usage entries %q: %w", fields[1], err)
	}
	if blocks < 0 {
		blocks = 0
	}
	if entries < 0 {
		entries = 0
	}
	return data.VolumeUsage{Bytes: blocks * 1024, Entries: entries}, nil
}

// EmptyVolume implements data.VolumeRestorer. `find -mindepth 1 -delete`
// removes dotfiles, hidden directories and nested symlinks without deleting
// the mount root; `rm -rf /data/*` is deliberately not used.
func (c *Compose) EmptyVolume(ctx context.Context, volumeName string) (data.OpResult, error) {
	return c.runVolumeHelper(ctx, volumeName, []string{volumeName + ":/data"},
		"sh", "-c", "find /data -mindepth 1 -delete")
}

// ExtractVolume implements data.VolumeRestorer. The root helper restores exact
// uid/gid, modes, setuid bits and hardlinks. The caller empties the volume
// first; a plain extraction would merge stale files.
func (c *Compose) ExtractVolume(ctx context.Context, volumeName, artifactDir string) (data.OpResult, error) {
	return c.runVolumeHelper(ctx, volumeName,
		[]string{volumeName + ":/data", artifactDir + ":/backup:ro"},
		"tar", "-C", "/data", "-xpzf", "/backup/"+data.ArchiveDataFile)
}

// VerifyVolume implements data.VolumeRestorer. The script is generated by the
// restore package from the validated manifest and mounted read-only.
func (c *Compose) VerifyVolume(ctx context.Context, volumeName, scriptPath string) (data.OpResult, error) {
	dir := scriptDir(scriptPath)
	return c.runVolumeHelper(ctx, volumeName,
		[]string{volumeName + ":/data:ro", dir + ":/verify:ro"},
		"sh", "/verify/check.sh")
}

// runVolumeHelper owns one helper container's full lifetime. Every exit path
// removes it by name and confirms it is gone before returning; the caller
// holds the stack lock, so a leaked helper can never become a later consumer.
func (c *Compose) runVolumeHelper(ctx context.Context, volumeName string, mounts []string, entrypoint string, args ...string) (data.OpResult, error) {
	name := "dcraft-restore-" + randomSuffix()
	createArgs := []string{
		"create", "--name", name,
		"--label", "dcraft.restore=1",
		"--label", "dcraft.restore.volume=" + volumeName,
	}
	for _, mount := range mounts {
		createArgs = append(createArgs, "-v", mount)
	}
	createArgs = append(createArgs, "--entrypoint", entrypoint, c.HelperImage())
	createArgs = append(createArgs, args...)

	createRes, createErr := c.run(ctx, execx.Command{Name: "docker", Args: createArgs})
	output := strings.TrimSpace(string(createRes.Stderr))
	if ctxErr := ctx.Err(); ctxErr != nil {
		return data.OpResult{Output: output}, c.finishHelper(name, ctxErr, output, true)
	}
	if createErr != nil {
		return data.OpResult{Output: output}, c.finishHelper(name, createErr, output, true)
	}
	if !createRes.Succeeded() {
		return data.OpResult{Output: output}, c.finishHelper(name,
			fmt.Errorf("data restore helper could not be created: status %d", createRes.ExitCode), output, true)
	}

	startRes, startErr := c.run(ctx, execx.Command{Name: "docker", Args: []string{"start", "-a", name}})
	startOutput := strings.TrimSpace(startRes.Combined())
	if output != "" && startOutput != "" {
		output += "\n"
	}
	output += startOutput
	if ctxErr := ctx.Err(); ctxErr != nil {
		return data.OpResult{Output: output}, c.finishHelper(name, ctxErr, output, false)
	}
	if startErr != nil {
		return data.OpResult{Output: output}, c.finishHelper(name, startErr, output, false)
	}
	if !startRes.Succeeded() {
		return data.OpResult{Output: output}, c.finishHelper(name,
			fmt.Errorf("data restore helper exited with status %d", startRes.ExitCode), output, false)
	}
	return data.OpResult{Output: output}, c.finishHelper(name, nil, output, false)
}

func scriptDir(path string) string {
	return filepath.Dir(path)
}
